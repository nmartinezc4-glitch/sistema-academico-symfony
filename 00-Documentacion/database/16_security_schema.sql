-- =====================================================================
-- 16_security_schema.sql
-- Sistema Académico · Identidad, roles y asignación docente
--
-- Seguridad de aplicación persistida en PostgreSQL.
-- Symfony Security sigue siendo responsable de autenticación/autorización.
-- La BD almacena identidad, roles, auditoría y relación docente-oferta.
-- =====================================================================

\set ON_ERROR_STOP on

BEGIN;

CREATE TABLE SIS_SEG_USUARIO (
    USU_ID               INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    USU_CORREO           VARCHAR(180) NOT NULL,
    USU_PASSWORD_HASH    VARCHAR(255) NOT NULL,
    USU_NOMBRES          VARCHAR(100) NOT NULL,
    USU_APELLIDOS        VARCHAR(100) NOT NULL,
    USU_FOTO_RUTA        VARCHAR(255),
    USU_ACTIVO           BOOLEAN      NOT NULL DEFAULT TRUE,
    USU_ULTIMO_ACCESO_EN TIMESTAMPTZ,
    USU_CREADO_EN        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    USU_ACTUALIZADO_EN   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT PK_SIS_SEG_USUARIO PRIMARY KEY (USU_ID),
    CONSTRAINT CK_USU_CORREO_NO_VACIO CHECK (btrim(USU_CORREO) <> ''),
    CONSTRAINT CK_USU_PASSWORD_HASH_NO_VACIO CHECK (btrim(USU_PASSWORD_HASH) <> ''),
    CONSTRAINT CK_USU_NOMBRES_NO_VACIO CHECK (btrim(USU_NOMBRES) <> ''),
    CONSTRAINT CK_USU_APELLIDOS_NO_VACIO CHECK (btrim(USU_APELLIDOS) <> '')
);

CREATE UNIQUE INDEX UX_USU_CORREO_LOWER
    ON SIS_SEG_USUARIO (lower(USU_CORREO));

CREATE TABLE SIS_SEG_ROL (
    ROL_ID               INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    ROL_CODIGO           VARCHAR(60)  NOT NULL,
    ROL_NOMBRE           VARCHAR(100) NOT NULL,
    ROL_DESCRIPCION      VARCHAR(255),
    ROL_ACTIVO           BOOLEAN      NOT NULL DEFAULT TRUE,
    ROL_CREADO_EN        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    ROL_ACTUALIZADO_EN   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT PK_SIS_SEG_ROL PRIMARY KEY (ROL_ID),
    CONSTRAINT UQ_ROL_CODIGO UNIQUE (ROL_CODIGO),
    CONSTRAINT CK_ROL_CODIGO CHECK (ROL_CODIGO ~ '^ROLE_[A-Z0-9_]+$'),
    CONSTRAINT CK_ROL_NOMBRE_NO_VACIO CHECK (btrim(ROL_NOMBRE) <> '')
);

CREATE TABLE SIS_SEG_USUARIO_ROL (
    USR_USU_ID           INTEGER      NOT NULL,
    USR_ROL_ID           INTEGER      NOT NULL,
    USR_ASIGNADO_EN      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT PK_SIS_SEG_USUARIO_ROL PRIMARY KEY (USR_USU_ID, USR_ROL_ID),
    CONSTRAINT FK_USR_USU FOREIGN KEY (USR_USU_ID)
        REFERENCES SIS_SEG_USUARIO (USU_ID) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT FK_USR_ROL FOREIGN KEY (USR_ROL_ID)
        REFERENCES SIS_SEG_ROL (ROL_ID) ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE TABLE SIS_SEG_AUDITORIA (
    AUD_ID               BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    AUD_USU_ID           INTEGER,
    AUD_ACCION           VARCHAR(80)  NOT NULL,
    AUD_ENTIDAD          VARCHAR(80),
    AUD_ENTIDAD_ID       VARCHAR(120),
    AUD_DETALLE          JSONB        NOT NULL DEFAULT '{}'::jsonb,
    AUD_IP               VARCHAR(45),
    AUD_CREADO_EN        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT PK_SIS_SEG_AUDITORIA PRIMARY KEY (AUD_ID),
    CONSTRAINT CK_AUD_ACCION_NO_VACIO CHECK (btrim(AUD_ACCION) <> ''),
    CONSTRAINT FK_AUD_USU FOREIGN KEY (AUD_USU_ID)
        REFERENCES SIS_SEG_USUARIO (USU_ID) ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE INDEX IX_AUD_USU_FECHA
    ON SIS_SEG_AUDITORIA (AUD_USU_ID, AUD_CREADO_EN DESC);

CREATE INDEX IX_AUD_ACCION_FECHA
    ON SIS_SEG_AUDITORIA (AUD_ACCION, AUD_CREADO_EN DESC);

CREATE TABLE SIS_ACA_DOCENTE_OFERTA (
    DOF_USU_ID           INTEGER      NOT NULL,
    DOF_OFE_ID           INTEGER      NOT NULL,
    DOF_ACTIVO           BOOLEAN      NOT NULL DEFAULT TRUE,
    DOF_CREADO_EN        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    DOF_ACTUALIZADO_EN   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT PK_SIS_ACA_DOCENTE_OFERTA PRIMARY KEY (DOF_USU_ID, DOF_OFE_ID),
    CONSTRAINT FK_DOF_USU FOREIGN KEY (DOF_USU_ID)
        REFERENCES SIS_SEG_USUARIO (USU_ID) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT FK_DOF_OFE FOREIGN KEY (DOF_OFE_ID)
        REFERENCES SIS_ACA_OFERTA_CURSO (OFE_ID) ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE INDEX IX_DOF_OFE_ACTIVO
    ON SIS_ACA_DOCENTE_OFERTA (DOF_OFE_ID, DOF_ACTIVO);

COMMIT;

\echo '16_security_schema.sql: seguridad y asignación docente creadas'
