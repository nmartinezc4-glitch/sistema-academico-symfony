-- =====================================================================
--  01_schema.sql
--  Sistema Académico (SIS_ACA) · PostgreSQL 16+
--
--  Contenido: tablas, columnas, tipos, NOT NULL, DEFAULT y PRIMARY KEY.
--  UNIQUE / CHECK / FOREIGN KEY se declaran en 02_constraints.sql.
--
--  Convención de nombres (aprobada en E1):
--    · Tabla   : SIS_ACA_<ENTIDAD>   (escrito en mayúsculas, SIN comillas;
--                PostgreSQL lo almacena en minúsculas: sis_aca_estudiante)
--    · Columna : <PREFIJO 3 LETRAS>_<CAMPO>          ej. EST_NOMBRES
--    · PK      : <PREFIJO>_ID                         ej. EST_ID
--    · FK      : <PREFIJO_LOCAL>_<PREFIJO_REF>_ID     ej. EPR_EST_ID
--    · Prefijos únicos por entidad (ver docs/data_dictionary.md).
--
--  Tipos:
--    · PK INTEGER GENERATED BY DEFAULT AS IDENTITY (compatible con la
--      estrategia IDENTITY de Doctrine DBAL 4; permite seeds explícitos).
--    · DATE para fechas académicas; TIMESTAMPTZ para auditoría operativa.
--    · NUMERIC(5,2) para notas (sin redondeo implícito).
--    · Estados: VARCHAR(20) + CHECK (no ENUM; ver docs/E1_ENTREGA.md).
-- =====================================================================

SET client_min_messages = warning;

-- ---------------------------------------------------------------------
-- POL · Política académica (reglas versionadas)
-- ---------------------------------------------------------------------
CREATE TABLE SIS_ACA_POLITICA_ACADEMICA (
    POL_ID               INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    POL_CODIGO           VARCHAR(30)  NOT NULL,
    POL_NOMBRE           VARCHAR(150) NOT NULL,
    POL_NOTA_APROBACION  NUMERIC(5,2) NOT NULL,
    POL_VIGENTE_DESDE    DATE         NOT NULL,
    POL_CREADO_EN        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    POL_ACTUALIZADO_EN   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT PK_SIS_ACA_POLITICA_ACADEMICA PRIMARY KEY (POL_ID)
);
COMMENT ON TABLE  SIS_ACA_POLITICA_ACADEMICA IS 'Reglas académicas versionadas. La vigencia termina el día anterior al inicio de la siguiente política (derivado en SIS_ACA_VW_POLITICA_LINEA_TIEMPO). Una política usada por un período queda protegida (T3).';
COMMENT ON COLUMN SIS_ACA_POLITICA_ACADEMICA.POL_CODIGO          IS 'Código único de la política. Ej.: POL-2026-01.';
COMMENT ON COLUMN SIS_ACA_POLITICA_ACADEMICA.POL_NOTA_APROBACION IS 'Nota mínima de aprobación (inclusive). Comparación literal, sin redondeo: 60.99 reprueba con 61.00.';
COMMENT ON COLUMN SIS_ACA_POLITICA_ACADEMICA.POL_VIGENTE_DESDE   IS 'Inicio de vigencia. Única: no puede haber dos políticas que inicien el mismo día.';

-- ---------------------------------------------------------------------
-- ANL · Año lectivo
-- ---------------------------------------------------------------------
CREATE TABLE SIS_ACA_ANIO_LECTIVO (
    ANL_ID               INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    ANL_ANIO             SMALLINT     NOT NULL,
    ANL_NOMBRE           VARCHAR(100) NOT NULL,
    ANL_FECHA_INICIO     DATE         NOT NULL,
    ANL_FECHA_FIN        DATE         NOT NULL,
    ANL_ESTADO           VARCHAR(20)  NOT NULL DEFAULT 'PLANIFICADO',
    ANL_CREADO_EN        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    ANL_ACTUALIZADO_EN   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT PK_SIS_ACA_ANIO_LECTIVO PRIMARY KEY (ANL_ID)
);
COMMENT ON TABLE  SIS_ACA_ANIO_LECTIVO IS 'Año lectivo (calendario real). Ej.: 2026.';
COMMENT ON COLUMN SIS_ACA_ANIO_LECTIVO.ANL_ANIO   IS 'Año calendario del ciclo lectivo. Único.';
COMMENT ON COLUMN SIS_ACA_ANIO_LECTIVO.ANL_ESTADO IS 'PLANIFICADO | ABIERTO | CERRADO.';

-- ---------------------------------------------------------------------
-- PER · Período académico (cuándo se cursó realmente)
-- ---------------------------------------------------------------------
CREATE TABLE SIS_ACA_PERIODO_ACADEMICO (
    PER_ID               INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    PER_ANL_ID           INTEGER      NOT NULL,
    PER_NUMERO           SMALLINT     NOT NULL,
    PER_NOMBRE           VARCHAR(100) NOT NULL,
    PER_FECHA_INICIO     DATE         NOT NULL,
    PER_FECHA_FIN        DATE         NOT NULL,
    PER_POL_ID           INTEGER      NOT NULL,
    PER_ESTADO           VARCHAR(20)  NOT NULL DEFAULT 'PLANIFICADO',
    PER_CREADO_EN        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PER_ACTUALIZADO_EN   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT PK_SIS_ACA_PERIODO_ACADEMICO PRIMARY KEY (PER_ID)
);
COMMENT ON TABLE  SIS_ACA_PERIODO_ACADEMICO IS 'Período real dentro de un año lectivo (Semestre I / II). Responde: ¿cuándo se cursó?';
COMMENT ON COLUMN SIS_ACA_PERIODO_ACADEMICO.PER_NUMERO IS 'Número del período dentro del año (1 = Semestre I, 2 = Semestre II).';
COMMENT ON COLUMN SIS_ACA_PERIODO_ACADEMICO.PER_POL_ID IS 'Política que evalúa los resultados del período. Debe ser la vigente en PER_FECHA_INICIO (T3). Si se omite, T3 la asigna.';
COMMENT ON COLUMN SIS_ACA_PERIODO_ACADEMICO.PER_ESTADO IS 'PLANIFICADO | ABIERTO | CERRADO. Solo ABIERTO admite INSERT/UPDATE/DELETE de resultados (T2, SA204 PERIODO_NO_ABIERTO).';

-- ---------------------------------------------------------------------
-- CAR · Carrera
-- ---------------------------------------------------------------------
CREATE TABLE SIS_ACA_CARRERA (
    CAR_ID               INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    CAR_CODIGO           VARCHAR(30)  NOT NULL,
    CAR_NOMBRE           VARCHAR(150) NOT NULL,
    CAR_DESCRIPCION      TEXT,
    CAR_ACTIVO           BOOLEAN      NOT NULL DEFAULT TRUE,
    CAR_CREADO_EN        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CAR_ACTUALIZADO_EN   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT PK_SIS_ACA_CARRERA PRIMARY KEY (CAR_ID)
);
COMMENT ON TABLE  SIS_ACA_CARRERA IS 'Catálogo de carreras de bachillerato.';
COMMENT ON COLUMN SIS_ACA_CARRERA.CAR_ACTIVO IS 'Desactivación lógica: una carrera con historial no se elimina, se desactiva.';

-- ---------------------------------------------------------------------
-- PEN · Pensum (versión curricular de una carrera)
-- ---------------------------------------------------------------------
CREATE TABLE SIS_ACA_PENSUM (
    PEN_ID               INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    PEN_CAR_ID           INTEGER      NOT NULL,
    PEN_CODIGO           VARCHAR(30)  NOT NULL,
    PEN_NOMBRE           VARCHAR(150) NOT NULL,
    PEN_VERSION          SMALLINT     NOT NULL,
    PEN_VIGENTE_DESDE    DATE         NOT NULL,
    PEN_VIGENTE_HASTA    DATE,
    PEN_ACTIVO           BOOLEAN      NOT NULL DEFAULT TRUE,
    PEN_CREADO_EN        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PEN_ACTUALIZADO_EN   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT PK_SIS_ACA_PENSUM PRIMARY KEY (PEN_ID)
);
COMMENT ON TABLE  SIS_ACA_PENSUM IS 'Pensum versionado de una carrera. El estudiante conserva el pensum con que inició.';
COMMENT ON COLUMN SIS_ACA_PENSUM.PEN_VERSION       IS 'Versión correlativa dentro de la carrera (1, 2, ...).';
COMMENT ON COLUMN SIS_ACA_PENSUM.PEN_VIGENTE_HASTA IS 'Último día en que se admiten nuevos estudiantes con este pensum. NULL = abierto. Pueden coexistir pensums de la misma carrera en transición.';

-- ---------------------------------------------------------------------
-- CIC · Ciclo curricular (dónde pertenece un curso dentro del pensum)
-- ---------------------------------------------------------------------
CREATE TABLE SIS_ACA_CICLO_CURRICULAR (
    CIC_ID               INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    CIC_ANIO             SMALLINT     NOT NULL,
    CIC_SEMESTRE         SMALLINT     NOT NULL,
    CIC_NOMBRE           VARCHAR(100) NOT NULL,
    CIC_ACTIVO           BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_SIS_ACA_CICLO_CURRICULAR PRIMARY KEY (CIC_ID)
);
COMMENT ON TABLE  SIS_ACA_CICLO_CURRICULAR IS 'Posición curricular global (Año 1 / Semestre I ...). Responde: ¿dónde pertenece la materia en el pensum? El orden se obtiene con (CIC_ANIO, CIC_SEMESTRE).';
COMMENT ON COLUMN SIS_ACA_CICLO_CURRICULAR.CIC_ANIO     IS 'Año curricular (1, 2, ...). No es un año calendario.';
COMMENT ON COLUMN SIS_ACA_CICLO_CURRICULAR.CIC_SEMESTRE IS 'Semestre dentro del año curricular (1, 2).';

-- ---------------------------------------------------------------------
-- CUR · Curso (catálogo maestro, sin duplicar por carrera)
-- ---------------------------------------------------------------------
CREATE TABLE SIS_ACA_CURSO (
    CUR_ID               INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    CUR_CODIGO           VARCHAR(30)  NOT NULL,
    CUR_NOMBRE           VARCHAR(150) NOT NULL,
    CUR_DESCRIPCION      TEXT,
    CUR_ACTIVO           BOOLEAN      NOT NULL DEFAULT TRUE,
    CUR_CREADO_EN        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CUR_ACTUALIZADO_EN   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT PK_SIS_ACA_CURSO PRIMARY KEY (CUR_ID)
);
COMMENT ON TABLE SIS_ACA_CURSO IS 'Catálogo maestro de cursos. Se vincula a pensums mediante SIS_ACA_PENSUM_CURSO.';

-- ---------------------------------------------------------------------
-- PCU · Curso dentro de un pensum y ciclo curricular
-- ---------------------------------------------------------------------
CREATE TABLE SIS_ACA_PENSUM_CURSO (
    PCU_ID               INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    PCU_PEN_ID           INTEGER      NOT NULL,
    PCU_CUR_ID           INTEGER      NOT NULL,
    PCU_CIC_ID           INTEGER      NOT NULL,
    PCU_OBLIGATORIO      BOOLEAN      NOT NULL DEFAULT TRUE,
    PCU_ORDEN            SMALLINT     NOT NULL,
    PCU_CREADO_EN        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PCU_ACTUALIZADO_EN   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT PK_SIS_ACA_PENSUM_CURSO PRIMARY KEY (PCU_ID)
);
COMMENT ON TABLE  SIS_ACA_PENSUM_CURSO IS 'Asignación PENSUM + CURSO + CICLO. Un curso aparece una sola vez por pensum.';
COMMENT ON COLUMN SIS_ACA_PENSUM_CURSO.PCU_OBLIGATORIO IS 'CONTRATO PARA SYMFONY. TRUE = obligatorio: cuenta para el avance (AVA_*), el estado del ciclo y el pensum completo. FALSE = optativo: se ofrece, se califica y aparece en historial y reportes, pero no suma ni resta al porcentaje. La interfaz debe distinguirlos con esta columna (no con el nombre del curso).';
COMMENT ON COLUMN SIS_ACA_PENSUM_CURSO.PCU_ORDEN       IS 'Orden de presentación dentro del ciclo.';

-- ---------------------------------------------------------------------
-- SEC · Sección
-- ---------------------------------------------------------------------
CREATE TABLE SIS_ACA_SECCION (
    SEC_ID               INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    SEC_CODIGO           VARCHAR(10)  NOT NULL,
    SEC_NOMBRE           VARCHAR(50)  NOT NULL,
    SEC_ACTIVO           BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_SIS_ACA_SECCION PRIMARY KEY (SEC_ID)
);
COMMENT ON TABLE SIS_ACA_SECCION IS 'Catálogo de secciones (A, B, C). El contexto lo dan SIS_ACA_ESTUDIANTE_PERIODO y SIS_ACA_OFERTA_CURSO.';

-- ---------------------------------------------------------------------
-- EST · Estudiante
-- ---------------------------------------------------------------------
CREATE TABLE SIS_ACA_ESTUDIANTE (
    EST_ID               INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    EST_CODIGO           VARCHAR(20)  NOT NULL,
    EST_NOMBRES          VARCHAR(100) NOT NULL,
    EST_APELLIDOS        VARCHAR(100) NOT NULL,
    EST_FECHA_NACIMIENTO DATE         NOT NULL,
    EST_DIRECCION        VARCHAR(255),
    EST_FOTO_RUTA        VARCHAR(255),
    EST_ACTIVO           BOOLEAN      NOT NULL DEFAULT TRUE,
    EST_CREADO_EN        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    EST_ACTUALIZADO_EN   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT PK_SIS_ACA_ESTUDIANTE PRIMARY KEY (EST_ID)
);
COMMENT ON TABLE  SIS_ACA_ESTUDIANTE IS 'Datos personales mínimos del estudiante. Sin contraseñas, datos médicos ni documentos sensibles.';
COMMENT ON COLUMN SIS_ACA_ESTUDIANTE.EST_NOMBRES          IS 'Nombres del estudiante (campo separado de apellidos, según enunciado).';
COMMENT ON COLUMN SIS_ACA_ESTUDIANTE.EST_APELLIDOS        IS 'Apellidos del estudiante.';
COMMENT ON COLUMN SIS_ACA_ESTUDIANTE.EST_CODIGO           IS 'Código único del estudiante (formato sugerido STU-AAAA-NNNN; no se impone con regex).';
COMMENT ON COLUMN SIS_ACA_ESTUDIANTE.EST_FECHA_NACIMIENTO IS 'Obligatoria. La validación de rango de edad se realiza en Symfony.';
COMMENT ON COLUMN SIS_ACA_ESTUDIANTE.EST_DIRECCION        IS 'Dirección de residencia. Campo opcional para compatibilidad con registros históricos.';
COMMENT ON COLUMN SIS_ACA_ESTUDIANTE.EST_FOTO_RUTA        IS 'Ruta relativa de la fotografía (ej. students/2026/STU-2026-0001.jpg). La imagen vive en el filesystem, nunca en la BD.';

-- ---------------------------------------------------------------------
-- EPR · Estudiante ↔ Pensum (programa)
-- ---------------------------------------------------------------------
CREATE TABLE SIS_ACA_ESTUDIANTE_PROGRAMA (
    EPR_ID               INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    EPR_EST_ID           INTEGER      NOT NULL,
    EPR_PEN_ID           INTEGER      NOT NULL,
    EPR_FECHA_INICIO     DATE         NOT NULL,
    EPR_FECHA_FIN        DATE,
    EPR_ESTADO           VARCHAR(20)  NOT NULL DEFAULT 'ACTIVO',
    EPR_CREADO_EN        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    EPR_ACTUALIZADO_EN   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT PK_SIS_ACA_ESTUDIANTE_PROGRAMA PRIMARY KEY (EPR_ID)
);
COMMENT ON TABLE  SIS_ACA_ESTUDIANTE_PROGRAMA IS 'Inscripción del estudiante en un pensum. La carrera se deriva de PEN_CAR_ID (decisión H1: sin columna de carrera redundante).';
COMMENT ON COLUMN SIS_ACA_ESTUDIANTE_PROGRAMA.EPR_PEN_ID IS 'Pensum con el que el estudiante inició. No migra automáticamente. Congelado si existen resultados (T4).';
COMMENT ON COLUMN SIS_ACA_ESTUDIANTE_PROGRAMA.EPR_ESTADO IS 'ACTIVO | FINALIZADO | RETIRADO. Solo un programa ACTIVO por estudiante.';

-- ---------------------------------------------------------------------
-- EPE · Estudiante en un período (ciclo y sección)
-- ---------------------------------------------------------------------
CREATE TABLE SIS_ACA_ESTUDIANTE_PERIODO (
    EPE_ID               INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    EPE_EPR_ID           INTEGER      NOT NULL,
    EPE_PER_ID           INTEGER      NOT NULL,
    EPE_CIC_ID           INTEGER      NOT NULL,
    EPE_SEC_ID           INTEGER      NOT NULL,
    EPE_ESTADO           VARCHAR(20)  NOT NULL DEFAULT 'INSCRITO',
    EPE_CREADO_EN        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    EPE_ACTUALIZADO_EN   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT PK_SIS_ACA_ESTUDIANTE_PERIODO PRIMARY KEY (EPE_ID)
);
COMMENT ON TABLE  SIS_ACA_ESTUDIANTE_PERIODO IS 'Ubicación del estudiante en un período: ciclo curricular y sección. Un registro por programa y período.';
COMMENT ON COLUMN SIS_ACA_ESTUDIANTE_PERIODO.EPE_CIC_ID IS 'Ciclo curricular que cursa el estudiante en el período (puede diferir del ciclo de un curso repetido).';
COMMENT ON COLUMN SIS_ACA_ESTUDIANTE_PERIODO.EPE_SEC_ID IS 'Sección del estudiante. Regla S1: debe coincidir con la sección de la oferta en que se registra la nota (T2).';
COMMENT ON COLUMN SIS_ACA_ESTUDIANTE_PERIODO.EPE_ESTADO IS 'INSCRITO | FINALIZADO | RETIRADO. Solo INSCRITO permite INSERT/UPDATE/DELETE de resultados (T2, SA205).';

-- ---------------------------------------------------------------------
-- OFE · Oferta de curso (curso del pensum + período + sección)
-- ---------------------------------------------------------------------
CREATE TABLE SIS_ACA_OFERTA_CURSO (
    OFE_ID               INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    OFE_PER_ID           INTEGER      NOT NULL,
    OFE_PCU_ID           INTEGER      NOT NULL,
    OFE_SEC_ID           INTEGER      NOT NULL,
    OFE_ACTIVO           BOOLEAN      NOT NULL DEFAULT TRUE,
    OFE_CREADO_EN        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    OFE_ACTUALIZADO_EN   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT PK_SIS_ACA_OFERTA_CURSO PRIMARY KEY (OFE_ID)
);
COMMENT ON TABLE SIS_ACA_OFERTA_CURSO IS 'Curso de un pensum impartido en un período y sección concretos.';
COMMENT ON COLUMN SIS_ACA_OFERTA_CURSO.OFE_ACTIVO IS 'FALSE = oferta inactiva: no admite INSERT/UPDATE/DELETE de resultados (T2, SA206) ni se sugiere en ingreso de notas.';

-- ---------------------------------------------------------------------
-- RES · Resultado de curso (un intento)
-- ---------------------------------------------------------------------
CREATE TABLE SIS_ACA_RESULTADO_CURSO (
    RES_ID               INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    RES_EPE_ID           INTEGER      NOT NULL,
    RES_OFE_ID           INTEGER      NOT NULL,
    RES_NOTA             NUMERIC(5,2),
    RES_CALIFICADO_EN    TIMESTAMPTZ,
    RES_CREADO_EN        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    RES_ACTUALIZADO_EN   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT PK_SIS_ACA_RESULTADO_CURSO PRIMARY KEY (RES_ID)
);
COMMENT ON TABLE  SIS_ACA_RESULTADO_CURSO IS 'Una fila = un intento del estudiante en una oferta. El estado (PENDIENTE/APROBADO/REPROBADO) NO se almacena: se deriva con la política del período. RES_EPE_ID y RES_OFE_ID son inmutables (T4); no se admite un nuevo intento de un curso ya aprobado (T2, SA207).';
COMMENT ON COLUMN SIS_ACA_RESULTADO_CURSO.RES_NOTA          IS 'NULL = pendiente. Si existe: 0 <= nota <= 100, NUMERIC(5,2) sin redondeo.';
COMMENT ON COLUMN SIS_ACA_RESULTADO_CURSO.RES_CALIFICADO_EN IS 'Momento de la calificación. Obligatorio si y solo si hay nota.';
